"""Generate shared read-contract artifacts from the pure Pydantic model."""
import json
from pathlib import Path

from app.services.architecture.design_spec import Design

ROOT = Path(__file__).resolve().parents[3]


def typescript(schema):
    def kind(value):
        if "$ref" in value:
            return value["$ref"].split("/")[-1]
        if "const" in value:
            return json.dumps(value["const"])
        if "enum" in value:
            return " | ".join(json.dumps(item) for item in value["enum"])
        for key, separator in (("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")):
            if key in value:
                return "(" + separator.join(kind(item) for item in value[key]) + ")"
        primitive = {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}
        if value.get("type") in primitive:
            return primitive[value["type"]]
        if value.get("type") == "array":
            return "Array<" + kind(value.get("items", {})) + ">"
        if value.get("type") == "object":
            required = set(value.get("required", []))
            fields = [json.dumps(name) + ("" if name in required else "?") + ": " + kind(item) + ";"
                      for name, item in value.get("properties", {}).items()]
            extra = value.get("additionalProperties", False)
            if value.get("patternProperties"):
                fields.append("[key: string]: " + " | ".join(kind(item) for item in value["patternProperties"].values()) + ";")
            if isinstance(extra, dict):
                fields.append("[key: string]: " + kind(extra) + ";")
            elif extra is True:
                fields.append("[key: string]: unknown;")
            return "{ " + " ".join(fields) + " }" if fields else "Record<string, never>"
        return "unknown"

    lines = ["// Generated by scripts.generate_design_contract. Edit the Python contract, then regenerate.",
             "// Runtime validation remains on the server; these types grant no deployment authority."]
    lines.extend("export type " + name + " = " + kind(value) + ";" for name, value in schema.get("$defs", {}).items())
    lines.append("export type CanonicalDesign = " + kind({key: value for key, value in schema.items() if key != "$defs"}) + ";")
    return "\n".join(lines) + "\n"


def main():
    schema = Design.model_json_schema()
    # Sort first so artifact ordering is deterministic on every platform.
    serialized = json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
    (ROOT / "fixtures/architecture/design-v2.schema.json").write_text(serialized, encoding="utf-8")
    (ROOT / "apps/web/src/components/architecture/canonical-types.ts").write_text(typescript(json.loads(serialized)), encoding="utf-8")
    print("Generated canonical JSON schema and TypeScript read contract.")


if __name__ == "__main__":
    main()

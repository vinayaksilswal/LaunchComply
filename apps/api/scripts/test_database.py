"""Fail-closed helpers for the disposable PostgreSQL test runner, not app settings."""
import re
from sqlalchemy.engine import make_url
from sqlalchemy.exc import ArgumentError


def validate_admin_url(value):
    try:
        url = make_url(value)
        valid = (url.drivername == "postgresql" and url.host in {"127.0.0.1", "::1"}
                 and url.database == "postgres" and url.username == "lc_test_admin"
                 and url.password and not url.query and 0 < (url.port or 5432) < 65536)
    except (ValueError, TypeError, ArgumentError):
        valid = False
    if not valid:
        raise ValueError("Use a loopback disposable PostgreSQL service, postgres database and lc_test_admin role; URL options are prohibited.")
    return url


def validate_generated_name(value):
    if not re.fullmatch(r"lc_pytest_[a-f0-9]{32}", value):
        raise ValueError("Refusing cleanup of a database or role not generated by this runner.")
    return value
